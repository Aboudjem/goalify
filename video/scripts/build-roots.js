// Writes index.html (the one root composition HyperFrames allows per project) for a chosen cut,
// from ONE cut table, so the scene files in compositions/ stay the single source of every shot:
//   node scripts/build-roots.js [main|vertical|short|demo]     (default: main)
// main      16:9 main cut  (1920x1080)
// vertical  9:16 main cut  (1080x1920; scenes re-lay themselves out via CSS/JS, not a crop)
// short     16:9 15 s cut  (beats 1, 2, 3, 8, 9)
// demo      16:9 muted README loop (condition -> preview -> proof)
// The committed index.html is always the main cut; scripts/render-all.sh restores it.
const fs = require("fs");
const path = require("path");

const SCENES = {
  open: "compositions/open.html", // beats 1+2: hook + problem
  turn: "compositions/turn.html", // beat 3
  brief: "compositions/brief.html", // beat 4
  condition: "compositions/condition.html", // beat 5
  preview: "compositions/preview.html", // beat 6
  nonstop: "compositions/nonstop.html", // beat 7
  proof: "compositions/proof.html", // beat 8
  cta: "compositions/cta.html", // beat 9
};

const MAIN = [
  ["open", 5.4],
  ["turn", 3.0],
  ["brief", 6.0],
  ["condition", 4.0],
  ["preview", 5.5],
  ["nonstop", 5.0],
  ["proof", 4.5],
  ["cta", 5.1],
];
const SHORT = [
  ["open", 5.4],
  ["turn", 3.0],
  ["proof", 3.6],
  ["cta", 3.4],
];
const DEMO = [
  ["condition", 4.0],
  ["preview", 5.5],
  ["proof", 3.6],
];

const CUTS = [
  {
    name: "main",
    title: "goalify 3.0 promo (16:9)",
    w: 1920,
    h: 1080,
    seq: MAIN,
    music: "assets/music-main.mp3",
    shots: [5.75, 20.2, 34.1],
    warp: ["nonstop"],
  },
  {
    name: "vertical",
    title: "goalify 3.0 promo (9:16)",
    w: 1080,
    h: 1920,
    seq: MAIN,
    music: "assets/music-main.mp3",
    shots: [5.75, 20.2, 34.1],
    warp: ["nonstop"],
  },
  {
    name: "short",
    title: "goalify 3.0 promo (15 s)",
    w: 1920,
    h: 1080,
    seq: SHORT,
    music: "assets/music-short.mp3",
    shots: [5.75, 12.4],
    warp: [],
  },
  {
    name: "demo",
    title: "goalify 3.0 demo loop",
    w: 1920,
    h: 1080,
    seq: DEMO,
    music: null,
    shots: [4.6],
    warp: [],
  },
];

const r2 = (x) => Math.round(x * 100) / 100;

const want = process.argv[2] || "main";
const c = CUTS.find((x) => x.name === want);
if (!c) {
  console.error("unknown cut " + want + "; use one of " + CUTS.map((x) => x.name).join(", "));
  process.exit(1);
}
{
  let t = 0;
  const hosts = [];
  const warp = [];
  c.seq.forEach(([id, dur], i) => {
    hosts.push(
      `      <div id="${id}" data-composition-id="${id}" data-composition-src="${SCENES[id]}" data-start="${r2(t)}" data-duration="${dur}" data-track-index="${i + 1}" data-track-kind="graphics" data-width="${c.w}" data-height="${c.h}" style="z-index: ${i + 2}"></div>`,
    );
    if (c.warp.includes(id)) warp.push(r2(t + 0.2), r2(t + dur - 0.1));
    t += dur;
  });
  const D = r2(t);
  const audio = c.music
    ? `\n      <audio id="music" src="${c.music}" data-start="0" data-duration="${D}" data-track-index="20" data-volume="1"></audio>`
    : "";
  const html = `<!doctype html>
<!-- GENERATED by scripts/build-roots.js (cut: ${c.name}): edit the cut table there, not this file. -->
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=${c.w}, height=${c.h}" />
    <title>${c.title}</title>
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.15.0/dist/gsap.min.js"></script>
    <link rel="stylesheet" href="assets/film.css" />
    <script src="assets/film.js"></script>
    <script>
      window.FILM_SKY = ${JSON.stringify({ dur: D, shots: c.shots, warp })};
    </script>
    <style>
      html,
      body {
        width: ${c.w}px;
        height: ${c.h}px;
      }
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="${D}" data-width="${c.w}" data-height="${c.h}">
      <div id="sky" data-composition-id="sky" data-composition-src="compositions/sky.html" data-start="0" data-duration="${D}" data-track-index="0" data-track-kind="graphics" data-width="${c.w}" data-height="${c.h}" style="z-index: 1"></div>
${hosts.join("\n")}${audio}
    </div>
    <script>
      window.__timelines = window.__timelines || {};
      window.__timelines["main"] = gsap.timeline({ paused: true });
    </script>
  </body>
</html>
`;
  fs.writeFileSync(path.join(__dirname, "..", "index.html"), html);
  console.log(
    `index.html <- ${c.name}: ${c.w}x${c.h}, ${D}s, scenes: ${c.seq.map((s) => s[0]).join(" > ")}`,
  );
}
